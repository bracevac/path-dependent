# Writes lean/Coercions/Selective/FsubCompare/Tables.lean from the recorded #eval outputs
# Family.out and Depth.out (`lake env lean lean/Coercions/Selective/FsubCompare/Family.lean`
# and `... Depth.lean`). Run from the repository root; the outputs are kept in OUT.
OUT='lean/Coercions/Selective/FsubCompare/gen'
import re
fam=open(OUT+'/Family.out').read()
blocks=re.split(r"\n(?=\[\()",fam.strip())
assert len(blocks)==11, len(blocks)
names=["selRows","mechRows","narrowRows","instOuterRows","instInnerRows","uRows","uMechRows","allInvHandRows","allInvMechRows","fcChainRows","fcURows"]
out=["import Coercions.Selective.FsubCompare.Depth","/-! Kernel-checked tables (GENERATED by gen/tables.py from the #eval output; each theorem re-computes the table by `decide +kernel`). -/","namespace Compare.Tables","open Compare.Fam Compare.Depth",""]
for nm,b in zip(names,blocks):
    out.append(f"theorem t_{nm} : {nm} = {b.strip()} := by decide +kernel\n")
dep=open(OUT+'/Depth.out').read()
ia=dep.index("[(0,")
ib=dep.index("[[1, 0,")
ic=dep.index("[[1, 0,")
out.append(f"theorem t_partA : partA = {dep[ia:ib].strip()} := by decide +kernel\n")
out.append(f"theorem t_stress : stressFlat = {dep[ic:].strip()} := by decide +kernel\n")
out.append("end Compare.Tables")
open('lean/Coercions/Selective/FsubCompare/Tables.lean','w').write("\n".join(out)+"\n")
