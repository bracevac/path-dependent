(** Structural path checking is stable under structural renaming. *)
Theorem Path_StructCheck_rename {n m : nat} {G : Ctx n}
    {R : Path n -> Path n -> Prop} {k : Kind}
    {p : Path n} {d : Tau n k} (H : Path_StructCheck G R p d)
    {f : FinFun.t n m} {D : Ctx m} {E : Path m -> Path m -> Prop}
    (rho : Path_StructRenaming G f D E) (Hrel : Path_RelHom R E f) :
    Path_StructCheck D E (Path_rename p f) (Tau_rename d f).
Proof.
  exact (proj1 Path_Sub_rename_mut _ _ _ _ _ _ H _ _ _ _ rho Hrel).
Qed.

(** Structural generalized subtyping is stable under structural renaming. *)
Theorem Tau_StructSub_rename {n m : nat} {G : Ctx n}
    {R : Path n -> Path n -> Prop} {k : Kind}
    {d1 d2 : Tau n k} (H : Tau_StructSub G R d1 d2)
    {f : FinFun.t n m} {D : Ctx m} {E : Path m -> Path m -> Prop}
    (rho : Path_StructRenaming G f D E) (Hrel : Path_RelHom R E f) :
    Tau_StructSub D E (Tau_rename d1 f) (Tau_rename d2 f).
Proof.
  exact (proj2 Path_Sub_rename_mut _ _ _ _ _ _ H _ _ _ _ rho Hrel).
Qed.

(** Opening discharges the scoped relation: the bound variable is replaced
    by [x], related to itself by ambient reflexivity. *)
Theorem Path_RelHom_openAt {n : nat}
    {R : Path n -> Path n -> Prop} (HR : Path_IsEquivCongr R)
    (x : Fin.t n) :
    Path_RelHom (Path_ScopedLift R) R (FinFun.openAt x).
Proof.
  intros p q Hpq.
  rewrite !Path_rename_openAt_eq_open_var.
  exact (Path_ScopedLift_open_paths HR Hpq
    (path_equiv_refl HR (path_var x))).
Qed.

(** If the replacement variable checks at the binder type, opening maps the
    extended context structurally into the outer context. *)
Theorem Path_StructRenaming_openAt {n : nat} {G : Ctx n}
    {R : Path n -> Path n -> Prop} {S : Ty n} {x : Fin.t n}
    (Hx : Path_StructCheck G R (path_var x) (tau_ty S)) :
    Path_StructRenaming (ctx_snoc G S) (FinFun.openAt x) G R.
Proof.
  intros y T Hy.
  refine (@Fin.cases' n y
    (fun y => Ctx_Binds (ctx_snoc G S) y T ->
      Path_StructCheck G R (path_var (FinFun.openAt x y))
        (tau_ty (Ty_rename T (FinFun.openAt x)))) _ _ Hy).
  - intro H0.
    assert (T = Ty_weaken S) as ->.
    { exact (Ctx_Binds_unique H0 (binds_here G S)). }
    rewrite FinFun.openAt_zero.
    unfold Ty_weaken. rewrite Ty_rename_rename,
      FinFun.openAt_weaken, Ty_rename_id. exact Hx.
  - intros z Hz.
    assert (T = Ty_weaken (Ctx_lookup G z)) as ->.
    { exact (Ctx_Binds_unique Hz
        (binds_there G S (Ctx_lookup G z) z (Ctx_lookup_binds G z))). }
    rewrite FinFun.openAt_succ.
    unfold Ty_weaken. rewrite Ty_rename_rename,
      FinFun.openAt_weaken, Ty_rename_id.
    apply path_struct_check_var. apply Ctx_lookup_binds.
Qed.

(** One-binder opening for structural path checking. *)
Theorem Path_StructCheck_open_var {n : nat} {G : Ctx n}
    {R : Path n -> Path n -> Prop} {S0 : Ty n} {x : Fin.t n}
    {k : Kind} {p : Path (S n)} {d : Tau (S n) k}
    (H : Path_StructCheck (ctx_snoc G S0) (Path_ScopedLift R) p d)
    (HR : Path_IsEquivCongr R)
    (Hx : Path_StructCheck G R (path_var x) (tau_ty S0)) :
    Path_StructCheck G R
      (Path_rename p (FinFun.openAt x))
      (Tau_rename d (FinFun.openAt x)).
Proof.
  exact (Path_StructCheck_rename H
    (Path_StructRenaming_openAt Hx) (Path_RelHom_openAt HR x)).
Qed.

(** One-binder opening for structural generalized subtyping. *)
Theorem Tau_StructSub_open_var {n : nat} {G : Ctx n}
    {R : Path n -> Path n -> Prop} {S0 : Ty n} {x : Fin.t n}
    {k : Kind} {d1 d2 : Tau (S n) k}
    (H : Tau_StructSub (ctx_snoc G S0) (Path_ScopedLift R) d1 d2)
    (HR : Path_IsEquivCongr R)
    (Hx : Path_StructCheck G R (path_var x) (tau_ty S0)) :
    Tau_StructSub G R
      (Tau_rename d1 (FinFun.openAt x))
