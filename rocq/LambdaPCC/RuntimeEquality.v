(** Opening substitutions at related paths are pointwise related. *)
Definition path_openAt_related {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {p q : Path n} (evidence : R p q) :
    forall x, R
      (subst_apply (path_subst_openAt p) x)
      (subst_apply (path_subst_openAt q) x).
Proof.
  intro x.
  refine (fin_case (P := fun x => R
      (subst_apply (path_subst_openAt p) x)
      (subst_apply (path_subst_openAt q) x)) _ _ x).
  - rewrite !subst_openAt_zero. exact evidence.
  - intro i. rewrite !subst_openAt_succ. exact (eq_refl operations (PVar i)).
Defined.

(** Normalize arbitrary replacement conversion to componentwise path
    congruence. *)
Fixpoint capture_runtime_conv_congruent {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {C D : CaptureSet n} (conversion : CaptureRuntimeConv R C D)
    {struct conversion} : CaptureRuntimeCongruent R C D.
Proof.
  destruct conversion.
  - exact (capture_runtime_congruent_refl operations C).
  - exact (capture_runtime_congruent_of_subst operations
      (rho1 := path_subst_openAt p) (rho2 := path_subst_openAt q)
      (path_openAt_related operations r) context).
  - exact CRCG_empty.
  - exact (CRCG_union
      (@capture_runtime_conv_congruent _ _ operations _ _ conversion1)
      (@capture_runtime_conv_congruent _ _ operations _ _ conversion2)).
  - exact (CRCG_singleton r).
  - exact (CRCG_select r).
Defined.

