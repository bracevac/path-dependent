    {R : Path n -> Path n -> Type} {S0 T : Shape n}
    (conversion : ShapeRuntimeCongruent R S0 T) {struct conversion} :
    ShapeRuntimeConv R S0 T
with tau_runtime_congruent_to_conv {n : nat}
    {R : Path n -> Path n -> Type} {k : Kind} {d e : Tau n k}
    (conversion : TauRuntimeCongruent R d e) {struct conversion} :
    TauRuntimeConv R d e.
Proof.
  - destruct conversion.
