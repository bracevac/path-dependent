(** Embed structural congruence into general runtime conversion. *)
Fixpoint capture_runtime_congruent_to_conv {n : nat}
    {R : Path n -> Path n -> Type} {C D : CaptureSet n}
    (conversion : CaptureRuntimeCongruent R C D) {struct conversion} :
    CaptureRuntimeConv R C D.
