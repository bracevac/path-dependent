(** Pointwise-related substitutions remain related after binder lifting. *)
Definition path_scoped_lift_pointwise {l n : nat}
    {R : Path n -> Path n -> Type} {rho1 rho2 : PathSubst l n}
    (related : forall x, R (subst_apply rho1 x) (subst_apply rho2 x)) :
    forall x, PathScopedLift R
      (subst_apply (path_subst_lift rho1) x)
      (subst_apply (path_subst_lift rho2) x).
Proof.
  intro x.
  refine (fin_case (P := fun x => PathScopedLift R
      (subst_apply (path_subst_lift rho1) x)
      (subst_apply (path_subst_lift rho2) x)) _ _ x).
  - rewrite !subst_lift_zero. exact SL_bound.
  - intro i. rewrite !subst_lift_succ. exact (SL_old (related i)).
Defined.

(** Componentwise structural view of runtime conversion. *)
Inductive CaptureRuntimeCongruent :
    forall {n : nat}, (Path n -> Path n -> Type) ->
      CaptureSet n -> CaptureSet n -> Type :=
| CRCG_empty {n : nat} {R : Path n -> Path n -> Type} :
    CaptureRuntimeCongruent R CEmpty CEmpty
| CRCG_union {n : nat} {R : Path n -> Path n -> Type}
    {C C' D D' : CaptureSet n} :
    CaptureRuntimeCongruent R C C' -> CaptureRuntimeCongruent R D D' ->
    CaptureRuntimeCongruent R (CUnion C D) (CUnion C' D')
| CRCG_singleton {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} : R p q ->
    CaptureRuntimeCongruent R (CSingleton p) (CSingleton q)
| CRCG_select {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} {a : Name} : R p q ->
    CaptureRuntimeCongruent R (CSelect p a) (CSelect q a)
with TyRuntimeCongruent :
    forall {n : nat}, (Path n -> Path n -> Type) -> Ty n -> Ty n -> Type :=
| TRCG_capt {n : nat} {R : Path n -> Path n -> Type}
    {C D : CaptureSet n} {S0 T : Shape n} :
    CaptureRuntimeCongruent R C D -> ShapeRuntimeCongruent R S0 T ->
    TyRuntimeCongruent R (TyCapt C S0) (TyCapt D T)
with ShapeRuntimeCongruent :
    forall {n : nat}, (Path n -> Path n -> Type) ->
      Shape n -> Shape n -> Type :=
| SRCG_top {n : nat} {R : Path n -> Path n -> Type} :
    ShapeRuntimeCongruent R ShTop ShTop
| SRCG_bot {n : nat} {R : Path n -> Path n -> Type} :
    ShapeRuntimeCongruent R ShBot ShBot
| SRCG_fun {n : nat} {R : Path n -> Path n -> Type}
    {S0 S' : Ty n} {T T' : Ty (S n)} :
    TyRuntimeCongruent R S0 S' ->
    TyRuntimeCongruent (PathScopedLift R) T T' ->
    ShapeRuntimeCongruent R (ShFun S0 T) (ShFun S' T')
| SRCG_pair {n : nat} {R : Path n -> Path n -> Type}
    {k : Kind} {S0 S' : Ty n} {a : Name} {d d' : Tau (S n) k} :
    TyRuntimeCongruent R S0 S' ->
    TauRuntimeCongruent (PathScopedLift R) d d' ->
    ShapeRuntimeCongruent R (ShPair S0 a d) (ShPair S' a d')
| SRCG_single {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} : R p q ->
    ShapeRuntimeCongruent R (ShSingle p) (ShSingle q)
| SRCG_selection {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} {a : Name} : R p q ->
    ShapeRuntimeCongruent R (ShTSel p a) (ShTSel q a)
with TauRuntimeCongruent :
    forall {n : nat}, (Path n -> Path n -> Type) ->
      forall {k : Kind}, Tau n k -> Tau n k -> Type :=
| TaRCG_term {n : nat} {R : Path n -> Path n -> Type}
    {T U : Ty n} : TyRuntimeCongruent R T U ->
    TauRuntimeCongruent R (TauTerm T) (TauTerm U)
| TaRCG_type {n : nat} {R : Path n -> Path n -> Type}
    {L L' U U' : Shape n} :
    ShapeRuntimeCongruent R L L' -> ShapeRuntimeCongruent R U U' ->
    TauRuntimeCongruent R (TauType L U) (TauType L' U')
| TaRCG_capture {n : nat} {R : Path n -> Path n -> Type}
    {C C' D D' : CaptureSet n} :
    CaptureRuntimeCongruent R C C' ->
    CaptureRuntimeCongruent R D D' ->
    TauRuntimeCongruent R (TauCapture C D) (TauCapture C' D').

Arguments CRCG_empty {n R}.
Arguments CRCG_union {n R C C' D D'} _ _.
Arguments CRCG_singleton {n R p q} _.
Arguments CRCG_select {n R p q a} _.
Arguments TRCG_capt {n R C D S0 T} _ _.
Arguments SRCG_top {n R}.
Arguments SRCG_bot {n R}.
Arguments SRCG_fun {n R S0 S' T T'} _ _.
Arguments SRCG_pair {n R k S0 S' a d d'} _ _.
Arguments SRCG_single {n R p q} _.
Arguments SRCG_selection {n R p q a} _.
Arguments TaRCG_term {n R T U} _.
Arguments TaRCG_type {n R L L' U U'} _ _.
Arguments TaRCG_capture {n R C C' D D'} _ _.

(** Reflexivity for the structural view. *)
Equations capture_runtime_congruent_refl {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (C : CaptureSet n) : CaptureRuntimeCongruent R C C
    by struct C :=
capture_runtime_congruent_refl operations CEmpty := CRCG_empty;
capture_runtime_congruent_refl operations (CUnion C D) :=
  CRCG_union (capture_runtime_congruent_refl operations C)
    (capture_runtime_congruent_refl operations D);
capture_runtime_congruent_refl operations (CSingleton p) :=
  CRCG_singleton (eq_refl operations p);
capture_runtime_congruent_refl operations (CSelect p a) :=
  CRCG_select (eq_refl operations p).

Equations ty_runtime_congruent_refl {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (T : Ty n) : TyRuntimeCongruent R T T by struct T :=
ty_runtime_congruent_refl operations (TyCapt C shape) :=
  TRCG_capt (capture_runtime_congruent_refl operations C)
    (shape_runtime_congruent_refl operations shape)
with shape_runtime_congruent_refl {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (shape : Shape n) : ShapeRuntimeCongruent R shape shape
    by struct shape :=
shape_runtime_congruent_refl operations ShTop := SRCG_top;
shape_runtime_congruent_refl operations ShBot := SRCG_bot;
shape_runtime_congruent_refl operations (ShFun dom cod) :=
  SRCG_fun (ty_runtime_congruent_refl operations dom)
    (ty_runtime_congruent_refl
      (path_scoped_lift_congruence operations) cod);
shape_runtime_congruent_refl operations (ShPair first a member) :=
  SRCG_pair (ty_runtime_congruent_refl operations first)
    (tau_runtime_congruent_refl
      (path_scoped_lift_congruence operations) member);
shape_runtime_congruent_refl operations (ShSingle p) :=
  SRCG_single (eq_refl operations p);
shape_runtime_congruent_refl operations (ShTSel p a) :=
  SRCG_selection (eq_refl operations p)
with tau_runtime_congruent_refl {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {k : Kind} (d : Tau n k) : TauRuntimeCongruent R d d by struct d :=
tau_runtime_congruent_refl operations (TauTerm T) :=
  TaRCG_term (ty_runtime_congruent_refl operations T);
tau_runtime_congruent_refl operations (TauType lower upper) :=
  TaRCG_type (shape_runtime_congruent_refl operations lower)
    (shape_runtime_congruent_refl operations upper);
tau_runtime_congruent_refl operations (TauCapture lower upper) :=
  TaRCG_capture (capture_runtime_congruent_refl operations lower)
    (capture_runtime_congruent_refl operations upper).

(** Symmetry for the structural view. *)
Fixpoint capture_runtime_congruent_symm {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {C D : CaptureSet n} (conversion : CaptureRuntimeCongruent R C D)
    {struct conversion} : CaptureRuntimeCongruent R D C.
Proof.
  destruct conversion.
  - exact CRCG_empty.
  - exact (CRCG_union
      (@capture_runtime_congruent_symm _ _ operations _ _ conversion1)
      (@capture_runtime_congruent_symm _ _ operations _ _ conversion2)).
  - exact (CRCG_singleton (eq_symm operations r)).
  - exact (CRCG_select (eq_symm operations r)).
Defined.

Fixpoint ty_runtime_congruent_symm {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {T U : Ty n} (conversion : TyRuntimeCongruent R T U)
    {struct conversion} : TyRuntimeCongruent R U T
with shape_runtime_congruent_symm {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {S0 T : Shape n} (conversion : ShapeRuntimeCongruent R S0 T)
    {struct conversion} : ShapeRuntimeCongruent R T S0
with tau_runtime_congruent_symm {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    {k : Kind} {d e : Tau n k} (conversion : TauRuntimeCongruent R d e)
    {struct conversion} : TauRuntimeCongruent R e d.
Proof.
  - destruct conversion.
    exact (TRCG_capt
      (capture_runtime_congruent_symm operations c)
      (@shape_runtime_congruent_symm _ _ operations _ _ s)).
  - destruct conversion.
    + exact SRCG_top.
    + exact SRCG_bot.
    + exact (SRCG_fun
        (@ty_runtime_congruent_symm _ _ operations _ _ t)
        (@ty_runtime_congruent_symm _ _
          (path_scoped_lift_congruence operations) _ _ t0)).
    + exact (SRCG_pair
        (@ty_runtime_congruent_symm _ _ operations _ _ t)
        (@tau_runtime_congruent_symm _ _
          (path_scoped_lift_congruence operations) _ _ _ t0)).
    + exact (SRCG_single (eq_symm operations r)).
    + exact (SRCG_selection (eq_symm operations r)).
  - destruct conversion.
    + exact (TaRCG_term
        (@ty_runtime_congruent_symm _ _ operations _ _ t)).
    + exact (TaRCG_type
        (@shape_runtime_congruent_symm _ _ operations _ _ s)
        (@shape_runtime_congruent_symm _ _ operations _ _ s0)).
    + exact (TaRCG_capture
        (capture_runtime_congruent_symm operations c)
        (capture_runtime_congruent_symm operations c0)).
Defined.

(** A path congruence maps pointwise-related substitutions to related
    paths. *)
Fixpoint path_eq_congruence_of_subst {l n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (rho1 rho2 : PathSubst l n)
    (related : forall x, R (subst_apply rho1 x) (subst_apply rho2 x))
    (p : Path l) {struct p} :
    R (path_subst p rho1) (path_subst p rho2).
Proof.
  destruct p.
  - exact (related f).
  - simp path_subst. apply (eq_fst operations).
    exact (@path_eq_congruence_of_subst _ _ _ operations rho1 rho2
      related p).
  - simp path_subst. apply (eq_sel operations).
    exact (@path_eq_congruence_of_subst _ _ _ operations rho1 rho2
      related p).
Defined.

Fixpoint capture_runtime_congruent_of_subst {l n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (rho1 rho2 : PathSubst l n)
    (related : forall x, R (subst_apply rho1 x) (subst_apply rho2 x))
    (C : CaptureSet l) {struct C} :
    CaptureRuntimeCongruent R (capture_subst C rho1) (capture_subst C rho2)
    .
Proof.
  destruct C.
  - exact CRCG_empty.
  - simp capture_subst. exact (CRCG_union
      (@capture_runtime_congruent_of_subst _ _ _ operations rho1 rho2
        related C1)
      (@capture_runtime_congruent_of_subst _ _ _ operations rho1 rho2
        related C2)).
  - simp capture_subst. exact (CRCG_singleton
      (path_eq_congruence_of_subst operations
        (rho1 := rho1) (rho2 := rho2) related p)).
  - simp capture_subst. exact (CRCG_select
      (path_eq_congruence_of_subst operations
        (rho1 := rho1) (rho2 := rho2) related p)).
Defined.

