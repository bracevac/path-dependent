  - exact (CRC_select r).
Defined.

Fixpoint ty_runtime_congruent_to_conv {n : nat}
    {R : Path n -> Path n -> Type} {T U : Ty n}
    (conversion : TyRuntimeCongruent R T U) {struct conversion} :
    TyRuntimeConv R T U
