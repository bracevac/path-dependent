(** Finite proof-relevant runtime path equality. *)
Inductive PathRuntimeEq {n : nat} (sigma : Store n) :
    Path n -> Path n -> Type :=
| PREq_refl (p : Path n) : PathRuntimeEq sigma p p
| PREq_symm {p q : Path n} :
    PathRuntimeEq sigma p q -> PathRuntimeEq sigma q p
| PREq_trans {p q r : Path n} :
    PathRuntimeEq sigma p q -> PathRuntimeEq sigma q r ->
    PathRuntimeEq sigma p r
| PREq_coresolve {p q : Path n} {referent : Referent n} :
    PathResolve sigma p referent -> PathResolve sigma q referent ->
    PathRuntimeEq sigma p q
| PREq_fst {p q : Path n} :
    PathRuntimeEq sigma p q -> PathRuntimeEq sigma (PFst p) (PFst q)
| PREq_sel {p q : Path n} :
    PathRuntimeEq sigma p q -> forall a : Name,
      PathRuntimeEq sigma (PSel p a) (PSel q a).

Arguments PREq_refl {n sigma} p.
Arguments PREq_symm {n sigma p q} _.
Arguments PREq_trans {n sigma p q r} _ _.
Arguments PREq_coresolve {n sigma p q referent} _ _.
Arguments PREq_fst {n sigma p q} _.
Arguments PREq_sel {n sigma p q} _ a.

(** Runtime equality preserves the full generalized-resolution graph. *)
Lemma path_runtime_eq_resolve_iff {n : nat} {sigma : Store n}
    {p q : Path n} (evidence : PathRuntimeEq sigma p q)
    (referent : Referent n) :
    PathResolve sigma p referent <-> PathResolve sigma q referent.
Proof.
  revert referent.
  induction evidence; intro target.
  - tauto.
  - specialize (IHevidence target). tauto.
  - specialize (IHevidence1 target).
    specialize (IHevidence2 target). tauto.
  - split; intro resolution.
    + pose proof (path_resolve_deterministic p0 resolution) as equality.
      destruct equality. exact p1.
    + pose proof (path_resolve_deterministic p1 resolution) as equality.
      destruct equality. exact p0.
  - split; intro resolution.
    + dependent elimination resolution.
      eapply PR_fst.
      * exact (proj1 (IHevidence (RLoc x0)) p1).
      * exact s.
    + dependent elimination resolution.
      eapply PR_fst.
      * exact (proj2 (IHevidence (RLoc x0)) p1).
      * exact s.
  - split; intro resolution.
    + dependent elimination resolution.
      * eapply PR_sel.
        -- exact (proj1 (IHevidence (RLoc x1)) p3).
        -- exact s0.
      * eapply PR_sel_miss.
        -- exact (proj1 (IHevidence (RLoc x2)) p5).
        -- exact s1.
        -- eassumption.
        -- exact p6.
    + dependent elimination resolution.
      * eapply PR_sel.
        -- exact (proj2 (IHevidence (RLoc x1)) p3).
        -- exact s0.
      * eapply PR_sel_miss.
        -- exact (proj2 (IHevidence (RLoc x2)) p5).
        -- exact s1.
        -- eassumption.
        -- exact p6.
Qed.

(** Runtime equality survives allocation. *)
Definition path_runtime_eq_weaken {n : nat} {sigma : Store n}
    {p q : Path n} (evidence : PathRuntimeEq sigma p q)
    (v : Tm n) (is_value : Tm_IsValue v) :
    PathRuntimeEq (StoreVal sigma v is_value) (path_weaken p) (path_weaken q).
Proof.
  induction evidence.
  - exact (PREq_refl (path_weaken p)).
  - exact (PREq_symm IHevidence).
  - exact (PREq_trans IHevidence1 IHevidence2).
  - exact (PREq_coresolve
      (path_resolve_weaken p0 (v := v) is_value)
      (path_resolve_weaken p1 (v := v) is_value)).
  - unfold path_weaken in *. simp path_rename in *.
    exact (PREq_fst IHevidence).
  - unfold path_weaken in *. simp path_rename in *.
    exact (PREq_sel IHevidence a).
Defined.

(** Least path congruence below one binder.  Its type is declared before
    the mutually recursive conversion families that use it. *)
Inductive PathScopedLift {n : nat} (R : Path n -> Path n -> Type) :
    Path (S n) -> Path (S n) -> Type :=
| SL_bound : PathScopedLift R (PVar FZ) (PVar FZ)
| SL_old {p q : Path n} :
    R p q -> PathScopedLift R (path_weaken p) (path_weaken q)
| SL_symm {p q : Path (S n)} :
    PathScopedLift R p q -> PathScopedLift R q p
| SL_trans {p q r : Path (S n)} :
    PathScopedLift R p q -> PathScopedLift R q r -> PathScopedLift R p r
| SL_fst {p q : Path (S n)} :
    PathScopedLift R p q -> PathScopedLift R (PFst p) (PFst q)
| SL_sel {p q : Path (S n)} {a : Name} :
    PathScopedLift R p q -> PathScopedLift R (PSel p a) (PSel q a).

Arguments SL_bound {n R}.
Arguments SL_old {n R p q} _.
Arguments SL_symm {n R p q} _.
Arguments SL_trans {n R p q r} _ _.
Arguments SL_fst {n R p q} _.
Arguments SL_sel {n R p q a} _.

(** Proof-relevant conversion generated by replacing related paths. *)
Inductive CaptureRuntimeConv :
    forall {n : nat}, (Path n -> Path n -> Type) ->
      CaptureSet n -> CaptureSet n -> Type :=
| CRC_refl {n : nat} {R : Path n -> Path n -> Type}
    {C : CaptureSet n} : CaptureRuntimeConv R C C
| CRC_replace {n : nat} {R : Path n -> Path n -> Type}
    (context : CaptureSet (S n)) {p q : Path n} :
    R p q -> CaptureRuntimeConv R
      (capture_open context p) (capture_open context q)
| CRC_empty {n : nat} {R : Path n -> Path n -> Type} :
    CaptureRuntimeConv R CEmpty CEmpty
| CRC_union {n : nat} {R : Path n -> Path n -> Type}
    {C C' D D' : CaptureSet n} :
    CaptureRuntimeConv R C C' -> CaptureRuntimeConv R D D' ->
    CaptureRuntimeConv R (CUnion C D) (CUnion C' D')
| CRC_singleton {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} : R p q ->
    CaptureRuntimeConv R (CSingleton p) (CSingleton q)
| CRC_select {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} {a : Name} : R p q ->
    CaptureRuntimeConv R (CSelect p a) (CSelect q a)
with TyRuntimeConv :
    forall {n : nat}, (Path n -> Path n -> Type) -> Ty n -> Ty n -> Type :=
| TRC_refl {n : nat} {R : Path n -> Path n -> Type} {T : Ty n} :
    TyRuntimeConv R T T
| TRC_replace {n : nat} {R : Path n -> Path n -> Type}
    (context : Ty (S n)) {p q : Path n} :
    R p q -> TyRuntimeConv R (ty_open context p) (ty_open context q)
| TRC_capt {n : nat} {R : Path n -> Path n -> Type}
    {C D : CaptureSet n} {S0 T : Shape n} :
    CaptureRuntimeConv R C D -> ShapeRuntimeConv R S0 T ->
    TyRuntimeConv R (TyCapt C S0) (TyCapt D T)
with ShapeRuntimeConv :
    forall {n : nat}, (Path n -> Path n -> Type) ->
      Shape n -> Shape n -> Type :=
| SRC_refl {n : nat} {R : Path n -> Path n -> Type} {S0 : Shape n} :
    ShapeRuntimeConv R S0 S0
| SRC_replace {n : nat} {R : Path n -> Path n -> Type}
    (context : Shape (S n)) {p q : Path n} :
    R p q -> ShapeRuntimeConv R
      (shape_open context p) (shape_open context q)
| SRC_top {n : nat} {R : Path n -> Path n -> Type} :
    ShapeRuntimeConv R ShTop ShTop
| SRC_bot {n : nat} {R : Path n -> Path n -> Type} :
    ShapeRuntimeConv R ShBot ShBot
| SRC_fun {n : nat} {R : Path n -> Path n -> Type}
    {S0 S' : Ty n} {T T' : Ty (S n)} :
    TyRuntimeConv R S0 S' ->
    TyRuntimeConv (PathScopedLift R) T T' ->
    ShapeRuntimeConv R (ShFun S0 T) (ShFun S' T')
| SRC_pair {n : nat} {R : Path n -> Path n -> Type}
    {k : Kind} {S0 S' : Ty n} {a : Name}
    {d d' : Tau (S n) k} :
    TyRuntimeConv R S0 S' ->
    TauRuntimeConv (PathScopedLift R) d d' ->
    ShapeRuntimeConv R (ShPair S0 a d) (ShPair S' a d')
| SRC_single {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} : R p q ->
    ShapeRuntimeConv R (ShSingle p) (ShSingle q)
| SRC_selection {n : nat} {R : Path n -> Path n -> Type}
    {p q : Path n} {a : Name} : R p q ->
    ShapeRuntimeConv R (ShTSel p a) (ShTSel q a)
with TauRuntimeConv :
    forall {n : nat}, (Path n -> Path n -> Type) ->
      forall {k : Kind}, Tau n k -> Tau n k -> Type :=
| TaRC_refl {n : nat} {R : Path n -> Path n -> Type}
    {k : Kind} {d : Tau n k} : TauRuntimeConv R d d
| TaRC_replace {n : nat} {R : Path n -> Path n -> Type}
    {k : Kind} (context : Tau (S n) k) {p q : Path n} :
    R p q -> TauRuntimeConv R (tau_open context p) (tau_open context q)
| TaRC_term {n : nat} {R : Path n -> Path n -> Type}
    {T U : Ty n} : TyRuntimeConv R T U ->
    TauRuntimeConv R (TauTerm T) (TauTerm U)
| TaRC_type {n : nat} {R : Path n -> Path n -> Type}
    {L L' U U' : Shape n} :
    ShapeRuntimeConv R L L' -> ShapeRuntimeConv R U U' ->
    TauRuntimeConv R (TauType L U) (TauType L' U')
| TaRC_capture {n : nat} {R : Path n -> Path n -> Type}
    {C C' D D' : CaptureSet n} :
    CaptureRuntimeConv R C C' -> CaptureRuntimeConv R D D' ->
    TauRuntimeConv R (TauCapture C D) (TauCapture C' D').

Arguments CRC_refl {n R C}.
Arguments CRC_replace {n R} context {p q} _.
Arguments CRC_empty {n R}.
Arguments CRC_union {n R C C' D D'} _ _.
Arguments CRC_singleton {n R p q} _.
Arguments CRC_select {n R p q a} _.
Arguments TRC_refl {n R T}.
Arguments TRC_replace {n R} context {p q} _.
Arguments TRC_capt {n R C D S0 T} _ _.
Arguments SRC_refl {n R S0}.
Arguments SRC_replace {n R} context {p q} _.
Arguments SRC_top {n R}.
Arguments SRC_bot {n R}.
Arguments SRC_fun {n R S0 S' T T'} _ _.
Arguments SRC_pair {n R k S0 S' a d d'} _ _.
Arguments SRC_single {n R p q} _.
Arguments SRC_selection {n R p q a} _.
Arguments TaRC_refl {n R k d}.
Arguments TaRC_replace {n R k} context {p q} _.
Arguments TaRC_term {n R T U} _.
Arguments TaRC_type {n R L L' U U'} _ _.
Arguments TaRC_capture {n R C C' D D'} _ _.

(** Project capture conversion from conversion of capturing types. *)
Equations ty_runtime_conv_capture_conversion {n : nat}
    {R : Path n -> Path n -> Type} {T U : Ty n}
    (conversion : TyRuntimeConv R T U) :
    CaptureRuntimeConv R (ty_capture_set T) (ty_capture_set U) :=
ty_runtime_conv_capture_conversion TRC_refl := CRC_refl;
ty_runtime_conv_capture_conversion
    (TRC_replace (TyCapt captures shape) evidence) :=
  CRC_replace captures evidence;
ty_runtime_conv_capture_conversion (TRC_capt captures shape) := captures.

(** Operations required of a proof-relevant path equality. *)
Record PathEqCongruence {n : nat} (R : Path n -> Path n -> Type) : Type := {
  eq_refl : forall p, R p p;
  eq_symm : forall p q, R p q -> R q p;
  eq_trans : forall p q r, R p q -> R q r -> R p r;
  eq_fst : forall p q, R p q -> R (PFst p) (PFst q);
  eq_sel : forall p q, R p q -> forall a, R (PSel p a) (PSel q a)
}.

Arguments eq_refl {n R} _ _.
Arguments eq_symm {n R} _ {p q} _.
Arguments eq_trans {n R} _ {p q r} _ _.
Arguments eq_fst {n R} _ {p q} _.
Arguments eq_sel {n R} _ {p q} _ _.

Definition path_runtime_eq_congruence {n : nat} (sigma : Store n) :
    PathEqCongruence (PathRuntimeEq sigma) :=
  {| eq_refl := fun p => PREq_refl p;
     eq_symm := fun _ _ e => PREq_symm e;
     eq_trans := fun _ _ _ e1 e2 => PREq_trans e1 e2;
     eq_fst := fun _ _ e => PREq_fst e;
     eq_sel := fun _ _ e a => PREq_sel e a |}.

Definition path_scoped_lift_refl_old {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (x : Fin n) : PathScopedLift R (PVar (FS x)) (PVar (FS x)).
Proof.
  assert (equation : path_weaken (PVar x) = PVar (FS x)).
  { unfold path_weaken. simp path_rename. rewrite weaken_apply. reflexivity. }
  rewrite <- equation. exact (SL_old (eq_refl operations (PVar x))).
Defined.

Equations path_scoped_lift_refl {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R)
    (p : Path (S n)) : PathScopedLift R p p :=
path_scoped_lift_refl operations (PVar FZ) := SL_bound;
path_scoped_lift_refl operations (PVar (FS x)) :=
  path_scoped_lift_refl_old operations x;
path_scoped_lift_refl operations (PFst p) :=
  SL_fst (path_scoped_lift_refl operations p);
path_scoped_lift_refl operations (PSel p a) :=
  SL_sel (path_scoped_lift_refl operations p).

Definition path_scoped_lift_congruence {n : nat}
    {R : Path n -> Path n -> Type} (operations : PathEqCongruence R) :
    PathEqCongruence (PathScopedLift R) :=
  {| eq_refl := path_scoped_lift_refl operations;
     eq_symm := fun _ _ e => SL_symm e;
     eq_trans := fun _ _ _ e1 e2 => SL_trans e1 e2;
     eq_fst := fun _ _ e => SL_fst e;
     eq_sel := fun _ _ e _ => SL_sel e |}.

(** Scoped runtime equality remains stable under ambient allocation. *)
Definition path_scoped_lift_weaken_runtime {n : nat} {sigma : Store n}
    {p q : Path (S n)}
    (evidence : PathScopedLift (PathRuntimeEq sigma) p q)
    (v : Tm n) (is_value : Tm_IsValue v) :
    PathScopedLift (PathRuntimeEq (StoreVal sigma v is_value))
      (path_rename p (ext (weaken n)))
      (path_rename q (ext (weaken n))).
Proof.
  induction evidence.
  - simp path_rename. exact SL_bound.
  - unfold path_weaken in *.
    rewrite !path_rename_rename, <- comp_weaken.
    pose proof (SL_old (path_runtime_eq_weaken r (v := v) is_value)) as old.
    unfold path_weaken in old. rewrite !path_rename_rename in old.
    exact old.
  - exact (SL_symm IHevidence).
  - exact (SL_trans IHevidence1 IHevidence2).
  - simp path_rename in *. exact (SL_fst IHevidence).
  - simp path_rename in *. exact (SL_sel IHevidence).
Defined.

(** Relation morphisms for simultaneous path substitution. *)
Definition PathSubstHom {n m : nat}
    (R : Path n -> Path n -> Type) (E : Path m -> Path m -> Type)
    (rho : PathSubst n m) : Type :=
  forall p q, R p q -> E (path_subst p rho) (path_subst q rho).

Definition path_scoped_lift_subst {n m : nat}
    {R : Path n -> Path n -> Type} {E : Path m -> Path m -> Type}
    {rho : PathSubst n m} {p q : Path (S n)}
    (map_old : PathSubstHom R E rho)
    (evidence : PathScopedLift R p q) :
    PathScopedLift E
      (path_subst p (path_subst_lift rho))
      (path_subst q (path_subst_lift rho)).
Proof.
  induction evidence.
  - simp path_subst. rewrite subst_lift_zero. exact SL_bound.
  - rewrite !path_weaken_subst_lift. exact (SL_old (map_old _ _ r)).
  - exact (SL_symm IHevidence).
  - exact (SL_trans IHevidence1 IHevidence2).
  - simp path_subst. exact (SL_fst IHevidence).
  - simp path_subst. exact (SL_sel IHevidence).
Defined.

Definition path_scoped_lift_open {n : nat}
    {R : Path n -> Path n -> Type} {p q : Path (S n)} {r s : Path n}
    (operations : PathEqCongruence R)
    (evidence : PathScopedLift R p q) (arguments : R r s) :
    R (path_open p r) (path_open q s).
Proof.
  revert r s arguments.
  induction evidence; intros r0 s0 arguments.
  - unfold path_open. simp path_subst.
    rewrite !subst_openAt_zero. exact arguments.
  - rewrite !path_weaken_open. exact r.
  - apply (eq_symm operations). apply IHevidence.
    apply (eq_symm operations). exact arguments.
  - eapply (eq_trans operations).
    + exact (IHevidence1 r0 s0 arguments).
    + exact (IHevidence2 s0 s0 (eq_refl operations s0)).
  - unfold path_open in *. simp path_subst in *.
    exact (eq_fst operations (IHevidence r0 s0 arguments)).
  - unfold path_open in *. simp path_subst in *.
    exact (eq_sel operations (IHevidence r0 s0 arguments) a).
Defined.

(** Conversion is natural under simultaneous substitution and a relation
    morphism. *)
Definition capture_runtime_conv_subst_replace {n m : nat}
    {R : Path n -> Path n -> Type} {E : Path m -> Path m -> Type}
