Fixpoint capture_runtime_conv_subst {n : nat}
    {R : Path n -> Path n -> Type} {C D : CaptureSet n}
    (conversion : CaptureRuntimeConv R C D) {struct conversion} :
    forall {m : nat} {E : Path m -> Path m -> Type}
      (rho : PathSubst n m), PathSubstHom R E rho ->
      CaptureRuntimeConv E (capture_subst C rho) (capture_subst D rho)
with ty_runtime_conv_subst {n : nat}
    {R : Path n -> Path n -> Type} {T U : Ty n}
    (conversion : TyRuntimeConv R T U) {struct conversion} :
    forall {m : nat} {E : Path m -> Path m -> Type}
      (rho : PathSubst n m), PathSubstHom R E rho ->
      TyRuntimeConv E (ty_subst T rho) (ty_subst U rho)
with shape_runtime_conv_subst {n : nat}
    {R : Path n -> Path n -> Type} {S0 T : Shape n}
    (conversion : ShapeRuntimeConv R S0 T) {struct conversion} :
    forall {m : nat} {E : Path m -> Path m -> Type}
      (rho : PathSubst n m), PathSubstHom R E rho ->
      ShapeRuntimeConv E (shape_subst S0 rho) (shape_subst T rho)
with tau_runtime_conv_subst {n : nat}
    {R : Path n -> Path n -> Type} {k : Kind} {d e : Tau n k}
    (conversion : TauRuntimeConv R d e) {struct conversion} :
    forall {m : nat} {E : Path m -> Path m -> Type}
      (rho : PathSubst n m), PathSubstHom R E rho ->
      TauRuntimeConv E (tau_subst d rho) (tau_subst e rho).
Proof.
  - intros m E rho map_paths. destruct conversion.
    + exact CRC_refl.
    + exact (capture_runtime_conv_subst_replace context r
        (rho := rho) map_paths).
    + exact CRC_empty.
    + exact (CRC_union
        (@capture_runtime_conv_subst _ _ _ _ conversion1 _ _ rho map_paths)
        (@capture_runtime_conv_subst _ _ _ _ conversion2 _ _ rho map_paths)).
    + exact (CRC_singleton (map_paths _ _ r)).
    + exact (CRC_select (map_paths _ _ r)).
  - intros m E rho map_paths. destruct conversion.
    + exact TRC_refl.
    + exact (ty_runtime_conv_subst_replace context r
        (rho := rho) map_paths).
    + exact (TRC_capt
        (@capture_runtime_conv_subst _ _ _ _ c _ _ rho map_paths)
        (@shape_runtime_conv_subst _ _ _ _ s _ _ rho map_paths)).
  - intros m E rho map_paths. destruct conversion.
    + exact SRC_refl.
    + exact (shape_runtime_conv_subst_replace context r
        (rho := rho) map_paths).
    + exact SRC_top.
    + exact SRC_bot.
    + exact (SRC_fun
        (@ty_runtime_conv_subst _ _ _ _ t _ _ rho map_paths)
        (@ty_runtime_conv_subst _ _ _ _ t0 _ _
          (path_subst_lift rho)
          (fun p q evidence => path_scoped_lift_subst map_paths evidence))).
    + exact (SRC_pair
        (@ty_runtime_conv_subst _ _ _ _ t _ _ rho map_paths)
        (@tau_runtime_conv_subst _ _ _ _ _ t0 _ _
          (path_subst_lift rho)
          (fun p q evidence => path_scoped_lift_subst map_paths evidence))).
    + exact (SRC_single (map_paths _ _ r)).
    + exact (SRC_selection (map_paths _ _ r)).
  - intros m E rho map_paths. destruct conversion.
    + exact TaRC_refl.
    + exact (tau_runtime_conv_subst_replace context r
        (rho := rho) map_paths).
    + exact (TaRC_term
        (@ty_runtime_conv_subst _ _ _ _ t _ _ rho map_paths)).
    + exact (TaRC_type
        (@shape_runtime_conv_subst _ _ _ _ s _ _ rho map_paths)
        (@shape_runtime_conv_subst _ _ _ _ s0 _ _ rho map_paths)).
    + exact (TaRC_capture
        (@capture_runtime_conv_subst _ _ _ _ c _ _ rho map_paths)
        (@capture_runtime_conv_subst _ _ _ _ c0 _ _ rho map_paths)).
Defined.

(** Renaming is substitution by the path embedding of a finite map. *)
Definition capture_runtime_conv_rename {n m : nat}
    {R : Path n -> Path n -> Type} {E : Path m -> Path m -> Type}
    {C D : CaptureSet n} (f : FinFun n m)
    (map_paths : forall p q, R p q ->
      E (path_rename p f) (path_rename q f))
    (conversion : CaptureRuntimeConv R C D) :
    CaptureRuntimeConv E (capture_rename C f) (capture_rename D f).
Proof.
  rewrite <- !capture_subst_as_rename.
  apply (capture_runtime_conv_subst conversion
    (rho := finfun_as_subst f)).
  intros p q evidence. rewrite !path_subst_as_rename.
  exact (map_paths p q evidence).
Defined.

Definition ty_runtime_conv_rename {n m : nat}
    {R : Path n -> Path n -> Type} {E : Path m -> Path m -> Type}
    {T U : Ty n} (f : FinFun n m)
    (map_paths : forall p q, R p q ->
      E (path_rename p f) (path_rename q f))
    (conversion : TyRuntimeConv R T U) :
